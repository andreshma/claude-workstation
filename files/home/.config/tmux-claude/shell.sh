# shellcheck shell=bash
# shellcheck source=/dev/null
#
# shell.sh — comfortable terminal: Tab completion, fzf, gray suggestions (ble.sh) and the AI
# copilot. Loaded by functions.sh in interactive shells only. To turn ble.sh off for one session:
# `ble-detach`; for good: `touch ~/.config/tmux-claude/no-ble`.
[[ $- == *i* ]] || return 0

# 1) ble.sh first (not attached yet): it replaces the line editor and brings
#    autosuggestions from history and syntax colors.
_ble="$HOME/.local/share/blesh/ble.sh"
if [[ -f "$_ble" && ! -f "$HOME/.config/tmux-claude/no-ble" && -z "${BLE_VERSION-}" ]]; then
  source "$_ble" --attach=none
fi
unset _ble

# 2) Tab completion: bash-completion + completions generated by ws-completions
#    (~/.local/share/bash-completion/completions, lazy-loaded per command).
if ! declare -F _init_completion >/dev/null && [[ -f /usr/share/bash-completion/bash_completion ]]; then
  source /usr/share/bash-completion/bash_completion
fi
# Completion for the workstation's own commands.
complete -W "this normal new worktree" tmux-solo
complete -W "install groups" ws-tools
complete -W "--now --if-due" ws-backup-lite
complete -W "--test --restore" ws-restore-lite
complete -W "--quick" ws-verify
complete -d tw twt two

# 3) fzf: Ctrl+R history, Ctrl+T file, Alt+C folder, **<Tab> paths.
if command -v fzf >/dev/null; then
  export FZF_DEFAULT_OPTS="--height 40% --layout=reverse --border"
  if [[ ${BLE_VERSION-} ]]; then
    ble-import -d integration/fzf-completion
    ble-import -d integration/fzf-key-bindings
  elif fzf --bash >/dev/null 2>&1; then
    eval "$(fzf --bash)"
  else
    for _f in /usr/share/doc/fzf/examples/key-bindings.bash /usr/share/bash-completion/completions/fzf; do
      [[ -f "$_f" ]] && source "$_f"
    done; unset _f
  fi
fi

# 4) AI copilot (Alt+a suggest · Alt+e explain · Alt+x fix).
[[ -f "$HOME/.config/tmux-claude/ai-shell.sh" ]] && source "$HOME/.config/tmux-claude/ai-shell.sh"

# 5) ble.sh attaches at the end, once everything above is defined.
# --- History without secrets (ws-patch30) ---
# A leading space in the command = it is not saved. Lines with credentials are not saved either.
HISTCONTROL=ignoreboth:erasedups
HISTIGNORE='*secret=*:*SECRET=*:*password=*:*PASSWORD=*:*passwd=*:*token=*:*TOKEN=*:*AccountKey=*:*SharedAccessSignature*:*ghp_*:*github_pat_*:*sk-ant-*:*AKIA*:*Bearer *:*--password*:*--client-secret*'

[[ ${BLE_VERSION-} ]] && ble-attach
